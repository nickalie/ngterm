def strip_comments(src: str) -> str:
    """Blank out comments, keeping string literals and newlines so offsets and line numbers hold."""
    out: list[str] = []
    i, n = 0, len(src)
    while i < n:
        if src.startswith("//", i):
            end = src.find("\n", i)
            end = n if end < 0 else end
            out.append(" " * (end - i))
            i = end
        elif src.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif src.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            out.append(re.sub(r"[^\n]", " ", src[i:j]))
            i = j
        elif src[i] == '"':
            end = _string_end(src, i)
            out.append(src[i:end])
            i = end
        else:
            out.append(src[i])
            i += 1
    return "".join(out)


def _string_end(src: str, i: int) -> int:
    """Index just past the string literal starting at `i` (plain or triple-quoted)."""
    quote = '"""' if src.startswith('"""', i) else '"'
    j = i + len(quote)
    while j < len(src):
        if src[j] == "\\":
            j += 2
        elif src.startswith(quote, j):
            return j + len(quote)
        else:
            j += 1
    return len(src)


def _matching_close(text: str, open_index: int, opener: str = "{", closer: str = "}") -> int:
    """Index of the `closer` matching the `opener` at `open_index`, skipping string literals."""
    depth, j = 0, open_index
    while j < len(text):
        c = text[j]
        if c == '"':
            j = _string_end(text, j)
            continue
        if c == opener:
            depth += 1
        elif c == closer:
            depth -= 1
            if depth == 0:
                return j
        j += 1
    raise CatalogError(f"unbalanced {opener}{closer}")


@dataclass
class Line:
    path: Path
    number: int
    text: str
    brace: int | None = None  # offset of the line's first depth-0 `{` in the source text


@dataclass
class TypeBody:
    path: Path
    text: str
    lines: list[Line]  # depth-1 lines of the body, comments blanked
    nested: dict[str, TypeBody]


def _top_lines(path: Path, text: str, start: int, end: int, first_line: int) -> list[Line]:
    """Lines of text[start:end] at nesting depth 0 relative to `start`; deeper text is dropped."""
    lines: list[Line] = []
    depth, buf, number, brace = 0, [], first_line, None
    j = start
    while j < end:
        c = text[j]
        if c == '"':
            k = _string_end(text, j)
            if depth == 0:
                buf.append(text[j:k])
            number += text.count("\n", j, k)
            j = k
            continue
        if c == "\n":
            if buf and "".join(buf).strip():
                lines.append(Line(path, number, "".join(buf).strip(), brace))
            buf, number, brace = [], number + 1, None
        elif c == "{":
            if depth == 0:
                buf.append("{")
                brace = j if brace is None else brace
            depth += 1
        elif c == "}":
            depth -= 1
        elif depth == 0:
            buf.append(c)
        j += 1
    if buf and "".join(buf).strip():
        lines.append(Line(path, number, "".join(buf).strip(), brace))
    return lines


_DECL = re.compile(r"\b(?:enum|struct|final\s+class|class|actor)\s+([A-Za-z_]\w*)\b[^{]*\{")


def find_type(sources: Mapping[Path, str], name: str) -> TypeBody:
    """The body of the one `enum`/`struct` named `name` across `sources` (comment-stripped texts)."""
    found: list[tuple[Path, str, int]] = []
    for path, text in sources.items():
        for match in _DECL.finditer(text):
            if match.group(1) == name and _depth_between(text, 0, match.start()) == 0:
                found.append((path, text, match.end() - 1))
    if not found:
        raise CatalogError(f"type {name} not found")
    if len(found) > 1:
        raise CatalogError(f"type {name} declared {len(found)} times: {', '.join(str(p) for p, _, _ in found)}")
    path, text, brace = found[0]
    return _type_body(path, text, brace)


def _type_body(path: Path, text: str, brace: int) -> TypeBody:
    end = _matching_close(text, brace)
    first_line = text.count("\n", 0, brace + 1) + 1
    lines = _top_lines(path, text, brace + 1, end, first_line)
    nested: dict[str, TypeBody] = {}
    offset = brace + 1
    while True:
        match = _DECL.search(text, offset, end)
        if match is None:
            break
        inner_brace = match.end() - 1
        # only direct children: a declaration whose brace sits at depth 1 of this body
        if _depth_between(text, brace + 1, match.start()) == 0:
            nested[match.group(1)] = _type_body(path, text, inner_brace)
        offset = _matching_close(text, inner_brace) + 1
    return TypeBody(path, text, lines, nested)


_EXTENSION = re.compile(r"\bextension\s+([A-Za-z_][\w.]*)\b[^{]*\{")


def find_extensions(sources: Mapping[Path, str], name: str) -> list[TypeBody]:
    """Bodies of every top-level `extension name` across `sources`."""
    return [
        _type_body(path, text, match.end() - 1)
        for path, text in sources.items()
        for match in _EXTENSION.finditer(text)
        if match.group(1) == name and _depth_between(text, 0, match.start()) == 0
    ]


def _depth_between(text: str, start: int, stop: int) -> int:
    depth, j = 0, start
    while j < stop:
        c = text[j]
        if c == '"':
            j = _string_end(text, j)
            continue
        depth += {"{": 1, "}": -1}.get(c, 0)
        j += 1
    return depth


_ATTRS = r"(?:@\w+(?:\([^)]*\))?\s+)*"
_CASE = re.compile(rf"^{_ATTRS}(?:indirect\s+)?case\s+(.*)$")
_CASE_ELEMENT = re.compile(r'^`?([A-Za-z_]\w*)`?(?:\s*=\s*"((?:[^"\\]|\\.)*)")?$')


def enum_raw_values(body: TypeBody, problems: list[str]) -> list[str]:
    """Raw values of a String enum in declaration order; an implicit raw value is the case name."""
    values: list[str] = []
    for line in body.lines:
        match = _CASE.match(line.text)
        if match is None:
            continue
        for element in _split_top(match.group(1)):
            m = _CASE_ELEMENT.match(element.strip())
            if m is None:
                problems.append(f"{line.path}:{line.number}: unparseable enum case: {line.text}")
                continue
            values.append(m.group(2) if m.group(2) is not None else m.group(1))
    return values


def _split_top(text: str) -> list[str]:
    parts, depth, buf, j = [], 0, "", 0
    while j < len(text):
        c = text[j]
        if c == '"':
            k = _string_end(text, j)
            buf += text[j:k]
            j = k
            continue
        if c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        if c == "," and depth == 0:
            parts.append(buf)
            buf = ""
        else:
            buf += c
        j += 1
    parts.append(buf)
    return parts


_MODIFIERS = (
    r"(?:(?:public|private|fileprivate|internal|open|package|static|class|lazy|weak|unowned|final|nonisolated"
    r"|override|dynamic)(?:\((?:set|unsafe)\))?\s+)*"
)
_PROPERTY = re.compile(rf"^{_ATTRS}({_MODIFIERS})(var|let)\s+(.*)$")
_BINDING = re.compile(r"\b(?:var|let)\b")
_STORED = re.compile(r"^`?([A-Za-z_]\w*)`?\s*:\s*[^=]+?(?:=.*)?$")
_ENCODE = re.compile(r"\bfunc\s+encode\s*\(\s*to\b")
_OBSERVER = re.compile(rf"^\s*{_ATTRS}(?:willSet|didSet)\b")


def _without_strings(text: str) -> str:
    out, j = [], 0
    while j < len(text):
        if text[j] == '"':
            j = _string_end(text, j)
            out.append('""')
        else:
            out.append(text[j])
            j += 1
    return "".join(out)


def codable_keys(body: TypeBody, problems: list[str], extensions: Sequence[TypeBody] = ()) -> list[str]:
    """JSON keys a synthesized Codable conformance encodes: CodingKeys when declared, else stored properties.

    Any shape this cannot read with certainty is a problem, never a guess.
    """
    for part in (body, *extensions):
        for line in part.lines:
            if _ENCODE.search(line.text):
                problems.append(f"{line.path}:{line.number}: custom encode(to:) — keys cannot be derived statically")
                return []
    for ext in extensions:
        if "CodingKeys" in ext.nested:
            problems.append(f"{ext.path}: CodingKeys declared in an extension — not read by the generator")
            return []
    if "CodingKeys" in body.nested:
        return enum_raw_values(body.nested["CodingKeys"], problems)
    keys: list[str] = []
    lines = body.lines
    for i, line in enumerate(lines):
        match = _PROPERTY.match(line.text)
        if match is None:
            if _BINDING.search(_without_strings(line.text)):
                problems.append(f"{line.path}:{line.number}: unparseable property: {line.text}")
            continue
        modifiers, rest = match.group(1), match.group(3).strip()
        if re.search(r"\b(?:static|class)\b", modifiers):
            continue
        brace = line.brace
        if brace is None and i + 1 < len(lines) and lines[i + 1].text.startswith("{"):
            brace = lines[i + 1].brace  # accessor block opened on the next line
        decl = rest.rstrip("{").strip()
        if brace is not None and "=" not in decl:
            block = body.text[brace + 1 : _matching_close(body.text, brace)]
            if not _OBSERVER.match(block):
                continue  # computed: get/set or a bare getter body
        if decl.endswith(","):
            problems.append(f"{line.path}:{line.number}: property declaration continues on the next line: {line.text}")
            continue
        for element in _split_top(decl):
            stored = _STORED.match(element.strip())
            if stored is None:
                problems.append(f"{line.path}:{line.number}: unparseable property: {line.text}")
                continue
            keys.append(stored.group(1))
    return keys


# --- commands.html ----------------------------------------------------------------------------------------

_SYNOPSIS_STYLE = ("color: #6d82f3", "font-size: 13.5px")
_WIRE_STYLE = ("color: #6b727a", "font-size: 11.5px")
_WORD = re.compile(r"^[a-z][a-z0-9-]*$")
_ALTERNATION = re.compile(r"^[a-z][a-z0-9-]*(?:\|[a-z][a-z0-9-]*)+$")
# A composite's wire line: the CLI subcommand sends no command of its own and uses the listed ones.
_CLI_ONLY = "CLI only:"


class _Cards(html.parser.HTMLParser):
    """Synopsis and wire-name blocks in document order, as (kind, text, line)."""

    def __init__(self) -> None:
        super().__init__()
        self.blocks: list[tuple[str, str, int]] = []
        self._stack: list[str | None] = []
        self._current: list[Any] | None = None

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        style = dict(attrs).get("style") or ""
        kind = None
        if tag == "div" and all(s in style for s in _SYNOPSIS_STYLE):
            kind = "synopsis"
        elif tag == "div" and all(s in style for s in _WIRE_STYLE):
            kind = "wire"
        if tag in ("br", "img", "hr", "input", "meta", "link"):
            return
        self._stack.append(kind)
        if kind:
            self._current = [kind, "", self.getpos()[0]]

    def handle_endtag(self, tag: str) -> None:
        if tag in ("br", "img", "hr", "input", "meta", "link") or not self._stack:
            return
        kind = self._stack.pop()
        if kind and self._current is not None:
            self.blocks.append((self._current[0], " ".join(self._current[1].split()), self._current[2]))
            self._current = None

    def handle_data(self, data: str) -> None:
        if self._current is not None:
            self._current[1] += data


@dataclass
class _Card:
    synopsis: str
    line: int
    wires: list[str] = field(default_factory=list)
    uses: list[str] | None = None  # a client-side composite's commands


def _cards(path: Path, text: str, commands: set[str], problems: list[str]) -> list[_Card]:
    parser = _Cards()
    parser.feed(text)
    parser.close()
    cards: list[_Card] = []
    for kind, block, line in parser.blocks:
        if kind == "synopsis":
            cards.append(_Card(block, line))
            continue
        if not cards or cards[-1].wires or cards[-1].uses is not None:
            problems.append(f"{path}:{line}: wire name without a synopsis: {block}")
            continue
        composite = block.startswith(_CLI_ONLY)
        separator = "," if composite else "·"
        body = block.removeprefix(_CLI_ONLY) if composite else block
        names = [w.strip() for w in body.split(separator) if w.strip()]
        for name in names:
            if name not in commands:
                problems.append(f"{path}:{line}: wire name {name} is not in the Command enum")
        if composite:
            cards[-1].uses = names
        else:
            cards[-1].wires = names
    return cards


def cli_subcommands(path: Path, text: str, commands: set[str], problems: list[str]) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for card in _cards(path, text, commands, problems):
        synopsis, line, wires = card.synopsis, card.line, card.wires
        invocations = [s.strip() for s in re.split(r"(?:^|\s)agtermctl\s+", " " + synopsis) if s.strip()]
        if not synopsis.startswith("agtermctl ") or not invocations:
            problems.append(f"{path}:{line}: synopsis does not start with agtermctl: {synopsis}")
            continue
        for invocation in invocations:
            for key, wire in _cli_keys(invocation, wires):
                if not key:
                    problems.append(f"{path}:{line}: no subcommand in synopsis: {invocation}")
                    continue
                if wire is None and wires:
                    problems.append(f"{path}:{line}: cannot tell which of {', '.join(wires)} `{key}` sends")
                    continue
                entry: dict[str, Any] = {"wire": wire} if wire else {}
                if card.uses is not None:
                    entry["uses"] = list(card.uses)
                if key in out and out[key] != entry:
                    problems.append(f"{path}:{line}: `{key}` maps to both {out[key]} and {entry}")
                out[key] = entry
    return out


def _cli_keys(invocation: str, wires: list[str]) -> Iterator[tuple[str, str | None]]:
    tokens = invocation.split()
    words: list[str] = []
    for token in tokens:
        if not _WORD.match(token):
            break
        words.append(token)
    rest = tokens[len(words) :]
    # `font inc|dec|reset` names three subcommands only when the card lists each one's wire name
    if words and rest and _ALTERNATION.match(rest[0]):
        dotted = [".".join([*words, alt]) for alt in rest[0].split("|")]
        if all(d in wires for d in dotted):
            for alt, wire in zip(rest[0].split("|"), dotted, strict=True):
                yield " ".join([*words, alt]), wire
            return
    key = " ".join(words)
    dotted_key = ".".join(words)
    if dotted_key in wires:
        yield key, dotted_key
    elif len(wires) == 1:
        yield key, wires[0]
    else:
        yield key, None


# --- UI identifiers ---------------------------------------------------------------------------------------

_UI_CALL = re.compile(r"\b(?:setAccessibilityIdentifier|accessibilityIdentifier)\s*\(")
_STRING_LIT = r'"(?:[^"\\\n]|\\.)*"'
_TERNARY = re.compile(rf"^([^\"?:]+?)\s+\?\s+({_STRING_LIT})\s*:\s*({_STRING_LIT})$")
_VARIABLE = re.compile(r"^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*$")
_INTERPOLATION = re.compile(r"\\\(\s*((?:self\.)?([A-Za-z_]\w*)(?:\.[A-Za-z_]\w*)*)\s*\)")
_UI_ID = re.compile(r"^[\w.{}-]+$")
_HELPER_CALL = re.compile(r"^Self\.([A-Za-z_]\w*)\s*\(")


def _blank_strings(text: str) -> str:
    """`text` with string-literal contents blanked, same length, so code matches never land inside a string."""
    out, j = [], 0
    while j < len(text):
        if text[j] == '"':
            k = _string_end(text, j)
            out.append(re.sub(r"[^\n]", " ", text[j:k]))
            j = k
        else:
            out.append(text[j])
            j += 1
    return "".join(out)


def _ui_literal(literal: str) -> str | None:
    """The id a string literal names, interpolations as `{name}` placeholders; None when it is not one."""
    body = literal[1:-1]
    if "{" in body or "}" in body:
        return None
    ui_id = _INTERPOLATION.sub(lambda m: "{" + m.group(2) + "}", body)
    return ui_id if "\\" not in ui_id and _UI_ID.match(ui_id) else None


def _enclosing_type(text: str, offset: int) -> tuple[int, int] | None:
    """(brace, end) of the innermost type declaration whose body holds `offset`."""
    best: tuple[int, int] | None = None
    for match in _DECL.finditer(text, 0, offset):
        brace = match.end() - 1
        try:
            end = _matching_close(text, brace)
        except CatalogError:
            continue
        if brace < offset < end and (best is None or brace > best[0]):
            best = (brace, end)
    return best


def _helper_call(arg: str) -> str | None:
    """The helper `name` when `arg` is one bare `Self.name(...)` call whose argument list closes at its end; None
    for anything else, a chained (`Self.name(x).uppercased()`) or compound (`Self.a(x) + Self.b(y)`) call included."""
    if (call := _HELPER_CALL.match(arg)) is None:
        return None
    try:
        close = _matching_close(arg, call.end() - 1, "(", ")")
    except CatalogError:
        return None
    return call.group(1) if close == len(arg) - 1 else None


def _helper_literal(text: str, offset: int, name: str) -> str | None:
    """The string literal a `Self.name(...)` call at `offset` returns: the body of the `static func name(...) ->
    String` declared directly in the enclosing type, when it is the only function of that name declared there (an
    overload of any form makes the call's target unknowable here) and its body is a single literal; None otherwise."""
    if (scope := _enclosing_type(text, offset)) is None:
        return None
    brace, end = scope
    declaration = re.compile(rf"\b(?:static|class)\s+func\s+{re.escape(name)}\b")
    declared = [
        m for m in declaration.finditer(text, brace + 1, end) if _depth_between(text, brace + 1, m.start()) == 0
    ]
    if len(declared) != 1:
        return None
    helper = re.compile(
        rf"static\s+func\s+{re.escape(name)}\s*\([^)]*\)\s*->\s*String\s*\{{\s*(?:return\s+)?({_STRING_LIT})\s*\}}"
    )
    found = helper.match(text, declared[0].start())
    return found.group(1) if found is not None else None


def ui_identifiers(path: Path, text: str, gen: Generated) -> None:
    """Add the ids set by every identifier call in `text` (comment-stripped) to `gen`."""
    for match in _UI_CALL.finditer(_blank_strings(text)):
        where = f"{path}:{text.count(chr(10), 0, match.start()) + 1}"
        try:
            arg = text[match.end() : _matching_close(text, match.end() - 1, "(", ")")].strip()
        except CatalogError:
            gen.problems.append(f"{where}: unbalanced identifier call")
            continue
        if (ternary := _TERNARY.match(arg)) is not None:
            literals = [ternary.group(2), ternary.group(3)]
        elif re.fullmatch(_STRING_LIT, arg):
            literals = [arg]
        elif (name := _helper_call(arg)) is not None and (helper := _helper_literal(text, match.start(), name)):
            literals = [helper]
        elif _VARIABLE.match(arg):
            gen.ui_variables.setdefault(f"{path}:{arg}", []).append(where)
            continue
        else:
            gen.problems.append(f"{where}: unparseable identifier argument: {' '.join(arg.split())}")
            continue
        for literal in literals:
            if (ui_id := _ui_literal(literal)) is None:
                gen.problems.append(f"{where}: unparseable identifier literal: {literal}")
                continue
            gen.ui_ids.setdefault(ui_id, {"at": []})["at"].append(where)


# --- generation and merge ---------------------------------------------------------------------------------


def generate(source: Path) -> Generated:
    gen = Generated()
    core = source / CORE
    sources = {p.relative_to(source): strip_comments(p.read_text()) for p in sorted(core.glob("*.swift"))}
    if not sources:
        gen.problems.append(f"no Swift sources under {core}")
        return gen

    def body(name: str) -> TypeBody | None:
        try:
            return find_type(sources, name)
        except CatalogError as error:
            gen.problems.append(str(error))
            return None

    if (commands := body(COMMAND_ENUM)) is not None:
        for raw in enum_raw_values(commands, gen.problems):
            gen.commands[raw] = {"mode": COMMAND_MODES[raw]} if raw in COMMAND_MODES else {}
    if (events := body(EVENT_ENUM)) is not None:
        gen.events = {raw: {} for raw in enum_raw_values(events, gen.problems)}
    for prefix, name in FIELD_SOURCES:
        if (node := body(name)) is not None:
            keys = codable_keys(node, gen.problems, find_extensions(sources, name))
            if not keys:
                gen.problems.append(f"{name}: no encoded properties found")
            gen.fields.update({f"{prefix}.{key}": {} for key in keys})
    html_path = source / COMMANDS_HTML
    if html_path.is_file():
        gen.cli = cli_subcommands(COMMANDS_HTML, html_path.read_text(), set(gen.commands), gen.problems)
    else:
        gen.problems.append(f"{COMMANDS_HTML} not found")
    for path in sorted((source / APP).rglob("*.swift")):
        ui_identifiers(path.relative_to(source), strip_comments(path.read_text()), gen)

    for section in GENERATED_SECTIONS:
        if not getattr(gen, section):
            gen.problems.append(f"no {section} found")
    if not gen.ui_ids:
        gen.problems.append(f"no ui ids found under {APP}")
    if gen.commands:
        named = set(COMMAND_MODES) | {k for k in AUTO_EXEMPTIONS if ":" not in k}
        for name in sorted(named - set(gen.commands)):
            gen.problems.append(f"generator table names {name}, which is not in the Command enum")
    return gen


@dataclass
class Changes:
    added: dict[str, list[str]] = field(default_factory=dict)
    removed: dict[str, list[str]] = field(default_factory=dict)


def _merge_section(
    section: str,
    previous: Mapping[str, Any],
    generated: Mapping[str, Mapping[str, Any]],
    generated_keys: Sequence[str],
    changes: Changes,
) -> dict[str, Any]:
    merged: dict[str, Any] = {}
    for key, items in generated.items():
        kept = {k: v for k, v in (previous.get(key) or {}).items() if k not in generated_keys}
        status = kept.pop("status", None)
        if key not in previous or status in (None, "removed-upstream"):
            status = "uncovered"
        if key not in previous:
            changes.added.setdefault(section, []).append(key)
        merged[key] = {"status": status, **items, **kept}
    for key, entry in previous.items():
        if key in merged:
            continue
        entry = dict(entry or {})
        if entry.get("status") != "removed-upstream":
            changes.removed.setdefault(section, []).append(key)
        entry.pop("status", None)
        merged[key] = {"status": "removed-upstream", **entry}
    return merged


def merge(old: Mapping[str, Any] | None, gen: Generated, tag: str) -> tuple[dict[str, Any], Changes]:
    old = old or {}
    catalog: dict[str, Any] = {"upstream": tag}
    changes = Changes()
    for section in GENERATED_SECTIONS:
        catalog[section] = _merge_section(
            section, old.get(section) or {}, getattr(gen, section), GENERATED_KEYS, changes
        )
    catalog["behaviors"] = dict(old.get("behaviors") or {})
    for key, entry in AUTO_BEHAVIORS.items():
        catalog["behaviors"].setdefault(key, dict(entry))
    catalog["exemptions"] = dict(old.get("exemptions") or {})
    for key, reason in AUTO_EXEMPTIONS.items():
        catalog["exemptions"].setdefault(key, reason)
    return catalog, changes


def merge_ui(old: Mapping[str, Any] | None, gen: Generated, tag: str) -> tuple[dict[str, Any], Changes]:
    """ui-ids.yaml: `ids` regenerated like a catalog section; `manual` kept, its status following its site.

    A variable call no manual entry names, or a malformed manual entry, raises: an id is never guessed.
    """
    old = old or {}
    if not isinstance(old, Mapping) or not isinstance(old.get("manual") or {}, Mapping):
        raise CatalogError(f"{UI_IDS_NAME}: expected a mapping with a `manual` mapping")
    changes = Changes()
    ids = _merge_section("ids", old.get("ids") or {}, gen.ui_ids, UI_GENERATED_KEYS, changes)
    manual: dict[str, Any] = {}
    problems: list[str] = []
    named: set[str] = set()
    for key, entry in (old.get("manual") or {}).items():
        site = entry.get("site") if isinstance(entry, Mapping) else None
        if not isinstance(site, str) or not site:
            problems.append(f"manual id {key}: needs a site (<file>:<expression>)")
            continue
        if key in gen.ui_ids:
            problems.append(f"manual id {key} is also generated from {', '.join(gen.ui_ids[key]['at'])}")
            continue
        named.add(site)
        status = entry.get("status")
        if site not in gen.ui_variables:
            if status != "removed-upstream":
                changes.removed.setdefault("manual", []).append(key)
            status = "removed-upstream"
        elif status in (None, "removed-upstream"):
            status = "uncovered"
        manual[key] = {"status": status, **{k: v for k, v in entry.items() if k != "status"}}
    for site, where in gen.ui_variables.items():
        if site not in named:
            problems.append(
                f"{', '.join(where)}: identifier passed through `{site.rsplit(':', 1)[1]}` — add the ids it carries "
                f"under `manual:` in {UI_IDS_NAME}, each with site: {site}"
            )
    if problems:
        raise CatalogError("ui ids need manual entries:\n  " + "\n  ".join(problems))
    return {"upstream": tag, "ids": ids, "manual": manual}, changes


class _Flow(dict):  # type: ignore[type-arg]
    pass


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(_Flow, lambda d, v: d.represent_mapping("tag:yaml.org,2002:map", v, flow_style=True))


def dump(catalog: Mapping[str, Any], header: str = HEADER, width: int = 120) -> str:
    """Sections as block mappings, one flow-style line per item."""
    doc: dict[str, Any] = {}
    for key, value in catalog.items():
        if isinstance(value, Mapping):
            doc[key] = {k: _Flow(v) if isinstance(v, Mapping) else v for k, v in value.items()}
        else:
            doc[key] = value
    body = yaml.dump(doc, Dumper=_Dumper, sort_keys=False, default_flow_style=False, width=width, allow_unicode=True)
    return header.format(tag=catalog["upstream"]) + body


def extract(repo: Path, tag: str, into: Path) -> None:
    """`git archive` the catalog sources at `tag` into `into`; the repository's checkout is never touched."""
    archive = subprocess.run(
        ["git", "-C", str(repo), "archive", "--format=tar", tag, *ARCHIVE_PATHS], capture_output=True, check=False
    )
    if archive.returncode != 0:
        raise CatalogError(f"git archive {tag} failed: {archive.stderr.decode(errors='replace').strip()}")
    with tarfile.open(fileobj=io.BytesIO(archive.stdout)) as tar:
        tar.extractall(into, filter="data")


def _load(path: Path) -> Any:
    return yaml.safe_load(path.read_text()) if path.exists() else None


def run(
    source: Path, catalog_path: Path, ui_path: Path, tag: str
) -> tuple[Changes, Changes, Generated, dict[str, Any]]:
    gen = generate(source)
    if gen.problems:
        raise CatalogError("unparseable upstream input:\n  " + "\n  ".join(gen.problems))
    catalog, changes = merge(_load(catalog_path), gen, tag)
    ui, ui_changes = merge_ui(_load(ui_path), gen, tag)
    catalog_path.write_text(dump(catalog))
    ui_path.write_text(dump(ui, UI_HEADER, width=UI_WIDTH))
    return changes, ui_changes, gen, ui


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tag", required=True, help="upstream tag the catalog describes, e.g. v0.36.0")
    origin = parser.add_mutually_exclusive_group(required=True)
    origin.add_argument("--repo", type=Path, help="upstream git checkout to read the tag from (git archive)")
    origin.add_argument("--source", type=Path, help="an already extracted upstream tree at the tag")
    parser.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    parser.add_argument("--ui-ids", type=Path, help=f"default: {UI_IDS_NAME} next to the catalog")
    args = parser.parse_args(argv)
    ui_path = args.ui_ids or args.catalog.with_name(UI_IDS_NAME)
    try:
        if args.source:
            changes, ui_changes, gen, ui = run(args.source, args.catalog, ui_path, args.tag)
        else:
            with tempfile.TemporaryDirectory(prefix="gen-catalog-") as tmp:
                extract(args.repo, args.tag, Path(tmp))
                changes, ui_changes, gen, ui = run(Path(tmp), args.catalog, ui_path, args.tag)
    except (CatalogError, OSError, yaml.YAMLError) as error:
        print(f"gen_catalog: {error}", file=sys.stderr)
        return 1
    counts = {section: len(getattr(gen, section)) for section in GENERATED_SECTIONS}
    counts["ids"] = len(gen.ui_ids)
    for section, count in counts.items():
        source = changes if section in GENERATED_SECTIONS else ui_changes
        added = source.added.get(section, [])
        _print_section(f"{section}: {count} upstream, +{len(added)} new", source.removed.get(section, []))
    # Manual entries are hand-added, so the line has no `+new`; every figure counts manual ids.
    live = sum(entry["status"] != "removed-upstream" for entry in ui["manual"].values())
    _print_section(
        f"manual: {live} ids at {len(gen.ui_variables)} variable sites", ui_changes.removed.get("manual", [])
    )
    return 0


def _print_section(summary: str, removed: list[str]) -> None:
    print(f"{summary}, -{len(removed)} removed-upstream")
    for key in removed:
        print(f"  removed-upstream: {key}")


if __name__ == "__main__":
    sys.exit(main())
